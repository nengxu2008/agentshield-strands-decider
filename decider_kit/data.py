"""Data for the agent's tools: synthetic, from a file, or from an API.

The /new-agent interview asks where the agent's data comes from:

    synthetic  generated here by the LLM (a Strands Agent with structured output), saved as JSON in
               agent/data/, so tools and demos are deterministic:
                   python -m decider_kit.data orders --n 20 \\
                       --describe "online-store orders, a few delivered, some processing, one lost" \\
                       --fields "order_id:str,item:str,amount:float,status:str"
    file       a CSV or JSON the participant already has: copy it into agent/data/ and load it
               with `load("<name>")`
    api        a real API called from a tool; keys go in .env (never in code), and a recorded
               sample in agent/data/ keeps tests and the demo working offline

`load(name)` reads agent/data/<name>.json or .csv for the tools.

Images (for a decision that looks at photos) come from, best first:
    1. the participant's own photos (phone pictures are fine);
    2. openly licensed photos from Wikimedia Commons, with author and licence recorded:
           python -m decider_kit.data images bananas --query "Nendran banana" --n 4
       writes agent/data/images/bananas-*.jpg and appends their credits to
       agent/data/images/SOURCES.md (keep it; the licences require attribution);
    3. an image model in their AWS account, if one is enabled.
Never draw the answer into a test image (a label such as "ROTTEN"): the decider would read the
text instead of looking at the produce, and the benchmark would measure nothing.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any

from .config import ROOT

DATA = ROOT / "agent" / "data"
TYPES = {"str": str, "int": int, "float": float, "bool": bool}


def load(name: str) -> list[dict[str, Any]]:
    """Rows from agent/data/<name>.json (a list of objects) or <name>.csv."""
    j, c = DATA / f"{name}.json", DATA / f"{name}.csv"
    if j.exists():
        return list(json.loads(j.read_text()))
    if c.exists():
        with c.open(newline="") as f:
            return list(csv.DictReader(f))
    raise FileNotFoundError(f"no agent/data/{name}.json or .csv")


def synthetic(name: str, describe: str, fields: dict[str, type], n: int = 20, save: bool = True) -> list[dict[str, Any]]:
    """`n` realistic rows with `fields`, generated by the LLM on LLM_PROVIDER through a Strands Agent."""
    from pydantic import BaseModel, create_model

    from .llm import ask

    Row = create_model(f"{name.title().replace('_', '')}Row", **{k: (t, ...) for k, t in fields.items()}, __base__=BaseModel)
    Rows = create_model("Rows", rows=(list[Row], ...), __base__=BaseModel)  # type: ignore[valid-type]
    prompt = (f"Create {n} realistic, varied rows of {describe}. Use plausible, specific values (no placeholders "
              f"like 'example' or 'test'), and include a few edge cases the agent must handle. Fields: "
              + ", ".join(f"{k} ({t.__name__})" for k, t in fields.items()))
    out, _ = ask(prompt, output_model=Rows, max_tokens=300 + 120 * n)
    rows = [r.model_dump() for r in out.rows]
    if save:
        DATA.mkdir(parents=True, exist_ok=True)
        (DATA / f"{name}.json").write_text(json.dumps(rows, indent=1) + "\n")
    return rows


def commons_images(name: str, query: str, n: int = 4, width: int = 640) -> list[Path]:
    """Download `n` openly licensed photos matching `query` from Wikimedia Commons, with credits."""
    import re
    import urllib.parse
    import urllib.request

    ua = {"User-Agent": "decider-hackathon-kit/1.0 (AWS User Group Madurai; https://www.awsugmdu.in)"}
    not_photo = re.compile(r"logo|screenshot|poster|diagram|map|panel|chart|icon|scores|stamp|drawing|illustration", re.I)

    def search(text: str) -> list[dict[str, Any]]:
        q = urllib.parse.urlencode({"action": "query", "format": "json", "generator": "search", "gsrnamespace": 6,
                                    "gsrsearch": f"{text} filemime:image/jpeg", "gsrlimit": 40, "prop": "imageinfo",
                                    "iiprop": "url|extmetadata|mime", "iiurlwidth": width})
        with urllib.request.urlopen(urllib.request.Request(f"https://commons.wikimedia.org/w/api.php?{q}", headers=ua), timeout=30) as r:
            found = json.loads(r.read()).get("query", {}).get("pages", {}).values()
        return [p for p in sorted(found, key=lambda p: p.get("index", 0)) if not not_photo.search(p.get("title", ""))]

    words = query.split()
    pages: list[dict[str, Any]] = []
    for k in range(len(words), 0, -1):  # broaden the query until there are enough photos
        seen = {p["title"] for p in pages}
        pages += [p for p in search(" ".join(words[:k])) if p["title"] not in seen]
        if len(pages) >= n:
            break
    out_dir = DATA / "images"
    out_dir.mkdir(parents=True, exist_ok=True)
    saved: list[Path] = []
    credits = []
    for p in pages:
        info = (p.get("imageinfo") or [{}])[0]
        meta = info.get("extmetadata", {})
        lic = meta.get("LicenseShortName", {}).get("value", "")
        if info.get("mime") != "image/jpeg" or not lic or "fair use" in lic.lower():
            continue
        url = info.get("thumburl") or info.get("url")
        ext = ".jpg"
        dest = out_dir / f"{name}-{len(saved) + 1}{ext}"
        with urllib.request.urlopen(urllib.request.Request(url, headers=ua), timeout=60) as r:
            dest.write_bytes(r.read())
        artist = " ".join(re.sub(r"<[^>]+>", " ", meta.get("Artist", {}).get("value", "unknown")).split())[:160]
        credits.append(f"- `{dest.name}`: {p['title']} by {artist}, {lic}, {info.get('descriptionurl', '')}")
        saved.append(dest)
        if len(saved) >= n:
            break
    if credits:
        src = out_dir / "SOURCES.md"
        head = "" if src.exists() else "# Image credits (Wikimedia Commons; keep this file, the licences require it)\n\n"
        with src.open("a") as f:
            f.write(head + "\n".join(credits) + "\n")
    return saved


def main() -> None:
    import sys

    if len(sys.argv) > 1 and sys.argv[1] == "images":
        ap = argparse.ArgumentParser(description="Openly licensed photos from Wikimedia Commons into agent/data/images/")
        ap.add_argument("cmd")
        ap.add_argument("name")
        ap.add_argument("--query", required=True)
        ap.add_argument("--n", type=int, default=4)
        a = ap.parse_args()
        got = commons_images(a.name, a.query, a.n)
        print(f"[data] {len(got)} images in agent/data/images/ (credits in SOURCES.md): " + ", ".join(p.name for p in got))
        return
    ap = argparse.ArgumentParser(description="Generate synthetic data for the agent's tools into agent/data/<name>.json")
    ap.add_argument("name")
    ap.add_argument("--describe", required=True, help="what the rows are, in plain words")
    ap.add_argument("--fields", required=True, help="name:type pairs, e.g. order_id:str,amount:float (str, int, float, bool)")
    ap.add_argument("--n", type=int, default=20)
    a = ap.parse_args()
    fields = {k.strip(): TYPES[t.strip()] for k, t in (p.split(":") for p in a.fields.split(","))}
    rows = synthetic(a.name, a.describe, fields, a.n)
    print(f"[data] wrote agent/data/{a.name}.json ({len(rows)} rows); first: {json.dumps(rows[0]) if rows else '-'}")


if __name__ == "__main__":
    main()
